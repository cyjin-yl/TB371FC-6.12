"""Read one qualified ordinary result after the owned QEMU child has exited.

Only the fixed guest path is queried. debugfs is never given -w; the image
is neither mounted nor replayed. An absent, partial, conflicting or damaged
receipt/file is a failed evidence contract, never a reconstructed success.
"""
import hashlib
import json
import os
from pathlib import Path
import re
import stat
import subprocess

GUEST_PATH = '/var/lib/tb371fc-r4f-proof/system-result.json'
MAX_BYTES = 4 * 1024**2
UUID = r'[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}'
RECEIPT = re.compile(r'TB371FC_R4F_VM_FILE status=(pass|fail) boot_id=(' + UUID +
                     r') profile_sha256=([0-9a-f]{64}) sha256=([0-9a-f]{64}) bytes=([0-9]+) END')


def receipt_from_serial(serial, profile_sha256):
    lines = serial.decode('utf-8', errors='replace').splitlines()
    candidates = [line for line in lines if 'TB371FC_R4F_VM_FILE' in line]
    if len(candidates) != 1:
        raise ValueError('exactly one complete same-boot result receipt is required')
    matched = RECEIPT.fullmatch(candidates[0])
    if matched is None:
        raise ValueError('result receipt is malformed or interleaved')
    status_value, boot, profile, digest, size_text = matched.groups()
    size = int(size_text)
    if profile != profile_sha256 or not 0 < size <= MAX_BYTES or str(size) != size_text:
        raise ValueError('result receipt profile/size is invalid')
    return {'status': status_value, 'boot_id': boot, 'profile_sha256': profile,
            'sha256': digest, 'size': size}


def metadata_from_stat(text):
    header = re.findall(r'^Inode:\s*([0-9]+)\s+Type:\s*(\S+)\s+Mode:\s*([0-7]+)\s+', text, re.M)
    owner = re.findall(r'^User:\s*([0-9]+)\s+Group:\s*([0-9]+)(?:\s+Project:\s*[0-9]+)?\s+Size:\s*([0-9]+)\s*$', text, re.M)
    links = re.findall(r'^Links:\s*([0-9]+)\s+', text, re.M)
    if len(header) != 1 or len(owner) != 1 or len(links) != 1:
        raise ValueError('debugfs did not return unambiguous inode metadata')
    return {'inode': int(header[0][0]), 'type': header[0][1], 'mode': int(header[0][2], 8),
            'uid': int(owner[0][0]), 'gid': int(owner[0][1]), 'size': int(owner[0][2]),
            'nlink': int(links[0])}


def extract(image, output, serial, profile_sha256):
    receipt = receipt_from_serial(serial, profile_sha256)
    if not output.is_dir() or output.is_symlink():
        raise ValueError('owned ordinary run output directory required')
    info = output.stat()
    if info.st_uid != os.geteuid():
        raise ValueError('run output owner differs')
    retained = output / 'guest-result.json'
    if retained.exists() or retained.is_symlink():
        raise FileExistsError('result retention destination already exists')
    descriptor = os.open(image, os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC)
    commands = []
    try:
        before = os.fstat(descriptor)
        if not stat.S_ISREG(before.st_mode):
            raise ValueError('ordinary closed VM image required')
        source = '/proc/self/fd/' + str(descriptor)

        def debugfs(request):
            command = ['/usr/sbin/debugfs', '-R', request, source]
            value = subprocess.run(command, capture_output=True, timeout=30,
                                   pass_fds=(descriptor,), env={**os.environ, 'LC_ALL': 'C'})
            item = {'request': request, 'exit_code': value.returncode,
                    'stdout': value.stdout.decode(errors='replace'),
                    'stderr': value.stderr.decode(errors='replace')}
            commands.append(item)
            if value.returncode != 0 or len(value.stdout) + len(value.stderr) > 32768:
                raise RuntimeError('bounded read-only debugfs request failed')
            return item['stdout']

        parents = {}
        for name in ('/var', '/var/lib', '/var/lib/tb371fc-r4f-proof'):
            observed = metadata_from_stat(debugfs('stat ' + name))
            if observed['type'] != 'directory' or observed['uid'] != 0 or observed['gid'] != 0:
                raise ValueError('guest result path crosses a non-directory or unexpected owner')
            if name.endswith('-proof') and observed['mode'] != 0o700:
                raise ValueError('guest result directory is not private mode 0700')
            parents[name] = observed
        inode = metadata_from_stat(debugfs('stat ' + GUEST_PATH))
        if not (inode['type'] == 'regular' and inode['uid'] == inode['gid'] == 0 and
                inode['mode'] == 0o600 and inode['nlink'] == 1 and inode['size'] == receipt['size']):
            raise ValueError('guest result is not the exact ordinary private file')
        # These paths are constants generated by this profile, not paths
        # supplied by a receipt or untrusted JSON.
        if not re.fullmatch(r'/[A-Za-z0-9_./-]+', str(retained)):
            raise ValueError('result retention path cannot be represented safely')
        debugfs('dump -p ' + GUEST_PATH + ' ' + str(retained))
        member = os.open(retained, os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC)
        try:
            first = os.fstat(member)
            if not (stat.S_ISREG(first.st_mode) and first.st_size == receipt['size'] and
                    first.st_uid == first.st_gid == 0 and stat.S_IMODE(first.st_mode) == 0o600 and
                    first.st_nlink == 1):
                raise ValueError('retained result ordinary-file metadata differs')
            with os.fdopen(member, 'rb', closefd=False) as stream:
                raw = stream.read(MAX_BYTES + 1)
            last = os.fstat(member)
            key = lambda item: (item.st_dev, item.st_ino, item.st_size, item.st_mtime_ns, item.st_ctime_ns)
            if key(first) != key(last) or len(raw) != first.st_size:
                raise ValueError('retained result changed while read')
        finally:
            os.close(member)
        if hashlib.sha256(raw).hexdigest() != receipt['sha256']:
            raise ValueError('closed image result differs from its same-boot receipt')
        envelope = json.loads(raw)
        required = {'schema_version': 1, 'phase': 'verify', 'status': receipt['status'],
                    'boot_id': receipt['boot_id'], 'profile_sha256': profile_sha256,
                    'guest_path': GUEST_PATH, 'writer_context': 'system_u:system_r:sysadm_t:s0',
                    'host_full_log_qualification_pending': True, 'complete_system_accepted': False,
                    'physical_hardware_tested': False}
        if (not isinstance(envelope, dict) or any(envelope.get(k) != v for k, v in required.items()) or
                not isinstance(envelope.get('progress'), list) or len(envelope['progress']) > 80 or
                type(envelope.get('writer_pid')) is not int or envelope['writer_pid'] <= 1):
            raise ValueError('closed image result envelope differs from the receipt/contract')
        declared = envelope.get('file_metadata', {})
        if any(declared.get(k) != inode[k] for k in ('uid', 'gid', 'mode', 'nlink')):
            raise ValueError('recorded file metadata does not match the actual inode')
        if not (isinstance(declared.get('inode_selinux_context'), str) and declared['inode_selinux_context']):
            raise ValueError('actual writer file context missing')
        if receipt['status'] == 'pass':
            if not isinstance(envelope.get('result'), dict) or envelope.get('failure') is not None:
                raise ValueError('successful evidence envelope has no complete result')
        elif not isinstance(envelope.get('failure'), dict):
            raise ValueError('failed evidence envelope lacks its failure record')
        after = os.fstat(descriptor)
        if key(before) != key(after):
            raise ValueError('source image changed during read-only result extraction')
        return {'qualified': True, 'receipt': receipt, 'guest_inode': inode, 'parent_inodes': parents,
                'retained_path': str(retained), 'envelope': envelope, 'debugfs_requests': commands,
                'image_opened_for_write': False, 'image_mounted': False,
                'filesystem_replayed_or_repaired': False, 'source_image_metadata_unchanged': True}
    finally:
        os.close(descriptor)
